def literal(v) -> str:
    """A Cypher literal for FalkorDB's parameter header."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)  # double-quoted, escapes inside
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(literal(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {literal(x)}" for k, x in v.items()) + "}"
    raise TypeError(f"no Cypher literal for {type(v).__name__}")


def statement(row) -> str:
    head = "CYPHER " + " ".join(f"{k}={literal(v)}" for k, v in row.params.items()) + " " if row.params else ""
    return head + row.query


def render(store: Store, stem: str, tool: str, args: dict, what: str) -> str:
    mark = len(store.trace)
    T.call(store, tool, dict(args), T.Context(agent="agent:queries", session="s-queries", at="2026-10-02T09:00:00Z"))
    rows = store.trace[mark:]
    scratch = {r.graph for r in rows if r.graph}
    lines = [f"// {stem}: {tool}({', '.join(f'{k}={v!r}' for k, v in args.items())})", f"// {what}",
             f"// Generated by scripts/export_queries.py from the tool's own trace (seed-42 corpus, FalkorDB "
             f"{falkordb_version(store.db)}); do not edit.",
             "// Each statement starts with FalkorDB's CYPHER parameter header; run them in order."]
    if scratch:
        lines.append("// Statements marked [scratch] run on a temporary graph the tool creates and deletes "
                     "(GRAPH.QUERY <tenant>__scratch ...); the others on the tenant's graph.")
    lines.append("")
    for n, r in enumerate(rows, 1):
        where = "scratch" if r.graph else "tenant"
        lines.append(f"// [{n}] [{where}] rows: {r.rows}")
        lines.append(statement(r) + ";")
        lines.append("")
    return "\n".join(lines)


def build_store(port: int, tenant: str = "queries") -> Store:
    """The seed-42 corpus in a fresh tenant. FalkorDB 6.x writes the committed files: 4.22 runs sampled
    betweenness several times (bridges), so its trace of 05-bridges is longer."""
    from falkordb import FalkorDB

    from honest_memory.corpus.generator import build, write_corpus
    from honest_memory.ingest import ingest_corpus

    s = Store(FalkorDB(host="localhost", port=port, socket_timeout=30), tenant)
    s.drop()
    with tempfile.TemporaryDirectory() as tmp:
        ingest_corpus(s, write_corpus(build(42), Path(tmp) / "corpus"))
    s.trace.clear()
    return s


def export(store: Store) -> dict[str, str]:
    return {f"{stem}.cypher": render(store, stem, tool, args, what) for stem, tool, args, what in CALLS}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=6390)
    a = ap.parse_args()
    store = build_store(a.port)
    try:
        files = export(store)
    finally:
        store.drop()
    OUT.mkdir(exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"wrote {len(files)} files to {OUT}")


if __name__ == "__main__":
    main()
